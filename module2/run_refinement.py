#!/usr/bin/env python3
"""Compile, simulate, critique, and revise a dynamics program in bounded rounds.

The initial dynamics_program.json may be supplied by the user or generated by
module2_dyn_program.py. The scene and robot hardware remain fixed. Revisions
can change only the plan's physical values and starting state.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Any


HERE = Path(__file__).resolve().parent
ALLOWED_DYNAMIC_FIELDS = {"initial_pose", "mass", "friction", "initial_velocity",
                          "initial_angular_velocity", "duration", "pos", "quat"}


def read(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def write(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def dynamics(program: dict[str, Any]) -> list[dict[str, Any]]:
    raw = program.get("simulator_dynamics", [])
    return raw.get("dynamic_objects", []) if isinstance(raw, dict) else raw


def allowed_revision(before: dict[str, Any], after: dict[str, Any]) -> list[str]:
    """Reject revisions to hardware, object identity, sources, or visuals."""
    errors = []
    if set(before) != set(after):
        errors.append("top-level program fields changed")
    for key in before:
        if key != "simulator_dynamics" and before[key] != after.get(key):
            errors.append("fixed program field changed: " + key)
    previous, candidate = dynamics(before), dynamics(after)
    previous_raw, candidate_raw = before.get("simulator_dynamics"), after.get("simulator_dynamics")
    if isinstance(previous_raw, dict):
        if not isinstance(candidate_raw, dict) or {key: value for key, value in previous_raw.items() if key != "dynamic_objects"} != {key: value for key, value in candidate_raw.items() if key != "dynamic_objects"}:
            errors.append("fixed simulator-dynamics fields changed")
    if not isinstance(candidate, list) or len(previous) != len(candidate):
        return errors + ["dynamic-object count changed"]
    for index, (old, new) in enumerate(zip(previous, candidate)):
        if not isinstance(new, dict) or set(old) != set(new):
            errors.append(f"dynamic object {index} schema changed")
            continue
        for field in old:
            if field not in ALLOWED_DYNAMIC_FIELDS and old[field] != new[field]:
                errors.append(f"dynamic object {index} identity/source changed: {field}")
        for field in ("mass", "friction"):
            if field in new and (not isinstance(new[field], (int, float)) or not 0 < float(new[field]) < (101 if field == "mass" else 3.01)):
                errors.append(f"dynamic object {index} has invalid {field}")
        pose = new.get("initial_pose", {})
        if isinstance(pose, dict) and isinstance(old.get("initial_pose"), dict) and set(pose) != set(old["initial_pose"]):
            errors.append(f"dynamic object {index} initial_pose schema changed")
        if pose and (not isinstance(pose, dict) or len(pose.get("pos", [])) != 3 or len(pose.get("quat", [])) != 4):
            errors.append(f"dynamic object {index} has invalid initial_pose")
    return errors


def revise(program: dict, feedback: dict) -> dict:
    key = os.environ.get("DASHSCOPE_API_KEY") or os.environ.get("OPENAI_API_KEY")
    if not key:
        raise RuntimeError("DASHSCOPE_API_KEY or OPENAI_API_KEY is required for automatic revision")
    from openai import OpenAI
    client = OpenAI(api_key=key, base_url=os.environ.get(
        "DASHSCOPE_BASE_URL", "https://dashscope.aliyuncs.com/compatible-mode/v1"))
    message = {
        "previous_program": program,
        "simulator_feedback": feedback,
        "instruction": "Return one full JSON dynamics program. Keep object identities, source meshes, robot hardware/control, visual effects, and all nonphysical fields exactly unchanged. Change only allowed physical values or starting poses/velocities. Do not claim success; the simulator decides.",
    }
    response = client.chat.completions.create(
        model=os.environ.get("C2W_TEXT_MODEL", "qwen3-coder-plus"),
        messages=[{"role": "system", "content": "You revise the physics and initial state of a Code2Worlds-2 dynamics program using measured simulator feedback. Return only JSON."},
                  {"role": "user", "content": json.dumps(message)}],
        temperature=0.2, response_format={"type": "json_object"})
    candidate = json.loads(response.choices[0].message.content)
    errors = allowed_revision(program, candidate)
    if errors:
        raise ValueError("revised program violates fixed scene/interface: " + "; ".join(errors))
    return candidate


def execute(script: str, *args: str) -> None:
    command = [sys.executable, str(HERE / script), *args]
    subprocess.run(command, check=True)


def run(export: Path, robot: Path, prompt: str | None, max_revisions: int) -> dict:
    m2 = export / "module2"
    program_path = m2 / "dynamics_program.json"
    if not program_path.is_file():
        if not prompt:
            raise FileNotFoundError("supply module2/dynamics_program.json or --prompt")
        execute("module2_dyn_program.py", str(export), prompt)
    history = []
    for round_id in range(max_revisions + 1):
        program = read(program_path)
        archive = m2 / "refinement" / f"round{round_id:02d}"
        write(archive / "dynamics_program.json", program)
        try:
            execute("module2_emit_dynamic_v2.py", str(export), str(robot))
            execute("module2_rollout_v2.py", str(export))
            execute("postproc_rollout_blender.py", str(export))
            execute("module2_sim_critic.py", str(export))
            critic = read(m2 / "critic_report.json")
            for filename in ("critic_report.json", "rollout_log.json"):
                if (m2 / filename).is_file():
                    (archive / filename).write_bytes((m2 / filename).read_bytes())
            accepted = critic.get("verdict", {}).get("valid") is True
            feedback = critic
            status = "accepted" if accepted else "rejected"
        except (subprocess.CalledProcessError, FileNotFoundError, ValueError) as exc:
            accepted = False
            feedback = {"execution_error": type(exc).__name__ + ": " + str(exc)}
            status = "execution_error"
        history.append({"round": round_id, "status": status, "feedback": feedback})
        write(archive / "round_result.json", history[-1])
        if accepted:
            break
        if round_id == max_revisions:
            break
        try:
            candidate = revise(program, feedback)
            write(archive / "revised_program.json", candidate)
            write(program_path, candidate)
        except (RuntimeError, ValueError) as exc:
            history[-1]["revision_error"] = str(exc)
            write(archive / "round_result.json", history[-1])
            break
    result = {"schema_version": "code2worlds2.refinement.v1", "accepted": accepted,
              "rounds": len(history), "history": history}
    write(m2 / "refinement" / "result.json", result)
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("export_dir", type=Path)
    parser.add_argument("robot_dir", type=Path)
    parser.add_argument("--prompt")
    parser.add_argument("--max-revisions", type=int, default=3)
    args = parser.parse_args()
    if not 0 <= args.max_revisions <= 10:
        parser.error("max-revisions must be in [0,10]")
    result = run(args.export_dir.resolve(), args.robot_dir.resolve(), args.prompt, args.max_revisions)
    print(json.dumps({"accepted": result["accepted"], "rounds": result["rounds"]}))
    return 0 if result["accepted"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
